# Demonstrate operator precedence
result1 = 10 + 5 * 2
result2 = (10 + 5) * 2
result3 = 20 / 5 * 2
result4 = 10 - 5 - 2
result5 = 2 ** 3 ** 2

# Display results
print("10 + 5 * 2 =", result1)
print("(10 + 5) * 2 =", result2)
print("20 / 5 * 2 =", result3)
print("10 - 5 - 2 =", result4)
print("2 ** 3 ** 2 =", result5)