# String
s = "Python Programming"
print("P in string:", "P" in s)
print("z not in string:", "z" not in s)

# List
lst = [10, 20, 30, 40]
print("20 in list:", 20 in lst)
print("50 not in list:", 50 not in lst)

# Tuple
t = (1, 2, 3, 4)
print("3 in tuple:", 3 in t)
print("5 not in tuple:", 5 not in t)

# Set
st = {10, 20, 30}
print("10 in set:", 10 in st)
print("40 not in set:", 40 not in st)

# Dictionary
d = {"name": "John", "age": 18}
print("name in dictionary:", "name" in d)
print("city not in dictionary:", "city" not in d)