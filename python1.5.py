# String to Float
str_num = "25"
float_num = float(str_num)
print("String to Float:", float_num)
print("Type:", type(float_num))

# Float to Integer
float_num = 25.75
int_num = int(float_num)
print("Float to Integer:", int_num)
print("Type:", type(int_num))

# Integer to String
int_num = 100
str_num = str(int_num)
print("Integer to String:", str_num)
print("Type:", type(str_num))